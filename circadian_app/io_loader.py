"""Data ingestion for Phyphox (.zip/.csv/.xlsx), generic phone sensor logs, synthetic demo data, and live Phyphox Remote Access recording."""

from __future__ import annotations

import csv
import io
import json
import os
import re
import threading
import time
import zipfile
from dataclasses import dataclass, field
from datetime import datetime, timedelta
from pathlib import Path
from typing import Any, Callable, Dict, List, Optional, Tuple, Union
from urllib.parse import urlencode
from urllib.request import urlopen

import numpy as np
import pandas as pd


@dataclass
class RawSensorDataset:
    """Container for ingested passive phone activity and/or light time-series data."""

    df: pd.DataFrame
    source_name: str
    source_type: str
    has_activity: bool
    has_light: bool
    metadata: Dict[str, Any] = field(default_factory=dict)


def _detect_delimiter(sample_text: str) -> str:
    """Detect CSV delimiter among comma, semicolon, and tab."""
    first_lines = "\n".join(sample_text.splitlines()[:10])
    counts = {d: first_lines.count(d) for d in [",", ";", "\t"]}
    best = max(counts, key=counts.get)
    return best if counts[best] > 0 else ","


def _read_tabular_bytes(raw_bytes: bytes, filename: str) -> pd.DataFrame:
    """Read CSV, TSV, or Excel bytes with automatic delimiter and decimal handling."""
    lower = filename.lower()
    if lower.endswith((".xlsx", ".xls")):
        return pd.read_excel(io.BytesIO(raw_bytes))

    text = raw_bytes.decode("utf-8-sig", errors="replace")
    delim = _detect_delimiter(text)
    df = pd.read_csv(io.StringIO(text), sep=delim)
    # Handle European decimal commas if semicolon-delimited and numeric cols came in as strings
    if delim == ";":
        for col in df.columns:
            if df[col].dtype == object:
                converted = pd.to_numeric(df[col].astype(str).str.replace(",", ".", regex=False), errors="coerce")
                if converted.notna().mean() > 0.7:
                    df[col] = converted
    return df


def _find_matching_column(columns: List[str], patterns: List[str]) -> Optional[str]:
    """Return the first column whose lowercased name matches any regex pattern."""
    lowered = [(c, str(c).strip().lower()) for c in columns]
    for pat in patterns:
        rx = re.compile(pat, re.IGNORECASE)
        for orig, low in lowered:
            if rx.search(low):
                return orig
    return None


def _parse_timestamps(
    df: pd.DataFrame,
    time_col: Optional[str] = None,
    start_datetime: Optional[datetime] = None,
) -> Tuple[pd.Series, str]:
    """Parse timestamps from datetime strings, Unix epoch seconds/ms, or relative seconds."""
    cols = list(df.columns)
    if time_col is None:
        time_col = _find_matching_column(
            cols,
            [
                r"^(timestamp|datetime|date_time|date\s*time|utc|local\s*time)$",
                r"(timestamp|datetime|date)",
                r"^time\s*\(s\)$",
                r"^(time|t|elapsed|seconds|sec|epoch)$",
            ],
        )
    if time_col is None:
        if any("Circadian Rhythmometry" in str(c) and "Report" in str(c) for c in cols):
            raise ValueError(
                "This is an analysis report generated by this app (circadian_report.xlsx), not sensor data. "
                "Upload the data file you analysed instead, e.g. a CSV with 'timestamp' and 'activity' columns."
            )
        raise ValueError(f"Could not detect a timestamp/time column in columns: {cols}")

    series = df[time_col]
    # Numeric check: could be Unix epoch (s or ms) or relative elapsed seconds
    numeric = pd.to_numeric(series, errors="coerce")
    if numeric.notna().mean() > 0.85:
        med = float(numeric.dropna().median())
        if med > 1e12:  # Unix ms
            dt = pd.to_datetime(numeric, unit="ms", utc=False)
            return dt, time_col
        if med > 1e9:  # Unix seconds
            dt = pd.to_datetime(numeric, unit="s", utc=False)
            return dt, time_col
        # Relative elapsed seconds (e.g., Phyphox "Time (s)")
        base = start_datetime or datetime.now().replace(hour=0, minute=0, second=0, microsecond=0)
        dt = pd.to_datetime(base) + pd.to_timedelta(numeric, unit="s")
        return dt, time_col

    dt = pd.to_datetime(series, errors="coerce")
    if dt.notna().mean() < 0.5:
        raise ValueError(f"Column '{time_col}' could not be parsed as timestamps or elapsed seconds.")
    return dt, time_col


def _extract_phyphox_start_time(zf: zipfile.ZipFile) -> Optional[datetime]:
    """Extract recording START timestamp from Phyphox meta/time.csv inside a zip export."""
    for name in zf.namelist():
        if name.lower().endswith("meta/time.csv") or name.lower() == "time.csv":
            try:
                raw = zf.read(name)
                meta_df = _read_tabular_bytes(raw, name)
                event_col = _find_matching_column(list(meta_df.columns), [r"event"])
                sys_time_col = _find_matching_column(list(meta_df.columns), [r"system\s*time$", r"system\s*time\s*\("])
                exp_time_col = _find_matching_column(list(meta_df.columns), [r"experiment\s*time"])
                text_col = _find_matching_column(list(meta_df.columns), [r"system\s*time\s*text"])

                if event_col is not None:
                    starts = meta_df[meta_df[event_col].astype(str).str.upper().str.contains("START", na=False)]
                    row = starts.iloc[0] if len(starts) > 0 else meta_df.iloc[0]
                else:
                    row = meta_df.iloc[0]

                exp_offset = float(row[exp_time_col]) if exp_time_col and pd.notna(row[exp_time_col]) else 0.0
                if sys_time_col and pd.notna(row[sys_time_col]):
                    unix_s = float(row[sys_time_col]) - exp_offset
                    return datetime.fromtimestamp(unix_s)
                if text_col and pd.notna(row[text_col]):
                    parsed = pd.to_datetime(str(row[text_col]), errors="coerce")
                    if pd.notna(parsed):
                        return parsed.to_pydatetime() - timedelta(seconds=exp_offset)
            except Exception:
                return None
    return None


def _extract_activity_and_light_columns(
    df: pd.DataFrame,
    column_overrides: Optional[Dict[str, str]] = None,
) -> Dict[str, pd.Series]:
    """Extract standardized sensor columns (ax, ay, az, linear_accel, activity, lux) from a DataFrame."""
    overrides = column_overrides or {}
    cols = list(df.columns)
    result: Dict[str, pd.Series] = {}

    # Light / illuminance
    light_col = overrides.get("light") or _find_matching_column(
        cols,
        [
            r"illuminance",
            r"\blux\b|\(lx\)",
            r"ambient.*light|^light\b",
        ],
    )
    if light_col and light_col in df.columns:
        result["lux"] = pd.to_numeric(df[light_col], errors="coerce")

    # Precomputed activity / counts / steps / ENMO
    act_col = overrides.get("activity") or _find_matching_column(
        cols,
        [
            r"^activity(_index|_counts)?$",
            r"\benmo\b|\bpim\b|\bzcm\b",
            r"step|counts|motion_index",
            r"absolute\s*acceleration|abs.*acc",
        ],
    )
    if act_col and act_col in df.columns:
        result["activity_raw"] = pd.to_numeric(df[act_col], errors="coerce")

    # 3-axis accelerometer (linear or total)
    ax_col = overrides.get("ax") or _find_matching_column(
        cols, [r"(linear\s*)?accel.*x\b", r"\bax\b", r"^x\s*\(m/s"]
    )
    ay_col = overrides.get("ay") or _find_matching_column(
        cols, [r"(linear\s*)?accel.*y\b", r"\bay\b", r"^y\s*\(m/s"]
    )
    az_col = overrides.get("az") or _find_matching_column(
        cols, [r"(linear\s*)?accel.*z\b", r"\baz\b", r"^z\s*\(m/s"]
    )
    if ax_col and ay_col and az_col:
        result["ax"] = pd.to_numeric(df[ax_col], errors="coerce")
        result["ay"] = pd.to_numeric(df[ay_col], errors="coerce")
        result["az"] = pd.to_numeric(df[az_col], errors="coerce")
        is_linear = any("linear" in str(c).lower() or "without g" in str(c).lower() for c in (ax_col, ay_col, az_col))
        result["is_linear_accel"] = pd.Series(is_linear, index=df.index)

    return result


def load_phyphox_zip(
    source: Union[str, Path, bytes, io.BytesIO],
    start_datetime: Optional[datetime] = None,
    source_name: str = "phyphox_export.zip",
) -> RawSensorDataset:
    """Load a Phyphox multi-sensor .zip archive (including meta/time.csv, Light, Accelerometer)."""
    if isinstance(source, (str, Path)):
        path = Path(source)
        source_name = path.name
        zf_ctx = zipfile.ZipFile(path, "r")
    elif isinstance(source, bytes):
        zf_ctx = zipfile.ZipFile(io.BytesIO(source), "r")
    else:
        zf_ctx = zipfile.ZipFile(source, "r")

    frames: List[pd.DataFrame] = []
    meta_info: Dict[str, Any] = {"zip_files": []}

    with zf_ctx as zf:
        meta_info["zip_files"] = zf.namelist()
        detected_start = start_datetime or _extract_phyphox_start_time(zf)
        meta_info["start_datetime"] = detected_start.isoformat() if detected_start else None

        for member in zf.namelist():
            low = member.lower()
            if low.endswith("/") or "meta/" in low or not low.endswith((".csv", ".tsv", ".xlsx", ".xls")):
                continue
            raw_bytes = zf.read(member)
            if not raw_bytes.strip():
                continue
            df = _read_tabular_bytes(raw_bytes, member)
            if df.empty:
                continue

            try:
                dt, tcol = _parse_timestamps(df, start_datetime=detected_start)
            except ValueError:
                continue

            extracted = _extract_activity_and_light_columns(df)
            if not extracted:
                continue

            sub = pd.DataFrame({"timestamp": dt})
            for k, v in extracted.items():
                sub[k] = v.values
            sub = sub.dropna(subset=["timestamp"])
            frames.append(sub)

    if not frames:
        raise ValueError("No valid sensor data (Light or Accelerometer/Activity) found in Phyphox zip archive.")

    combined = pd.concat(frames, ignore_index=True, sort=False).sort_values("timestamp").reset_index(drop=True)
    has_light = "lux" in combined.columns and combined["lux"].notna().any()
    has_activity = any(
        c in combined.columns and combined[c].notna().any() for c in ("activity_raw", "ax", "ay", "az")
    )
    return RawSensorDataset(
        df=combined,
        source_name=source_name,
        source_type="phyphox_zip",
        has_activity=has_activity,
        has_light=has_light,
        metadata=meta_info,
    )


def load_tabular_sensor_file(
    source: Union[str, Path, bytes, io.BytesIO],
    filename: Optional[str] = None,
    start_datetime: Optional[datetime] = None,
    column_overrides: Optional[Dict[str, str]] = None,
) -> RawSensorDataset:
    """Load a CSV, TSV, or Excel sensor export (Phyphox, Sensor Logger, Actigraphy, or generic)."""
    if isinstance(source, (str, Path)):
        path = Path(source)
        filename = filename or path.name
        raw_bytes = path.read_bytes()
    elif isinstance(source, bytes):
        filename = filename or "sensor_data.csv"
        raw_bytes = source
    else:
        filename = filename or "sensor_data.csv"
        raw_bytes = source.read()

    if filename.lower().endswith(".zip"):
        return load_phyphox_zip(raw_bytes, start_datetime=start_datetime, source_name=filename)

    df = _read_tabular_bytes(raw_bytes, filename)
    if df.empty:
        raise ValueError(f"Uploaded file '{filename}' is empty.")

    overrides = column_overrides or {}
    dt, time_col = _parse_timestamps(df, time_col=overrides.get("time"), start_datetime=start_datetime)
    extracted = _extract_activity_and_light_columns(df, column_overrides=overrides)
    if not extracted:
        raise ValueError(
            f"Could not detect Activity/Accelerometer or Light/Lux columns in '{filename}'. "
            f"Available columns: {list(df.columns)}"
        )

    out = pd.DataFrame({"timestamp": dt})
    for k, v in extracted.items():
        out[k] = v.values
    out = out.dropna(subset=["timestamp"]).sort_values("timestamp").reset_index(drop=True)

    has_light = "lux" in out.columns and out["lux"].notna().any()
    has_activity = any(c in out.columns and out[c].notna().any() for c in ("activity_raw", "ax", "ay", "az"))

    return RawSensorDataset(
        df=out,
        source_name=filename,
        source_type="tabular_file",
        has_activity=has_activity,
        has_light=has_light,
        metadata={"time_column": time_col, "original_columns": list(df.columns)},
    )


def merge_datasets(datasets: List[RawSensorDataset]) -> RawSensorDataset:
    """Merge multiple loaded sensor datasets (e.g., separate Light.csv and Accelerometer.csv)."""
    if not datasets:
        raise ValueError("No datasets provided to merge.")
    if len(datasets) == 1:
        return datasets[0]

    frames = [d.df for d in datasets]
    combined = pd.concat(frames, ignore_index=True, sort=False).sort_values("timestamp").reset_index(drop=True)
    has_light = "lux" in combined.columns and combined["lux"].notna().any()
    has_activity = any(c in combined.columns and combined[c].notna().any() for c in ("activity_raw", "ax", "ay", "az"))
    return RawSensorDataset(
        df=combined,
        source_name=" + ".join(d.source_name for d in datasets),
        source_type="merged",
        has_activity=has_activity,
        has_light=has_light,
        metadata={"sources": [d.source_name for d in datasets]},
    )


def generate_synthetic_circadian_data(
    days: int = 14,
    epoch_minutes: float = 5,
    start_date: Optional[datetime] = None,
    tau_hours: float = 24.0,
    acrophase_hour: float = 14.5,
    shift_day: Optional[int] = 8,
    shift_hours: float = 3.5,
    harmonic_2_amp_ratio: float = 0.28,
    harmonic_3_amp_ratio: float = 0.12,
    noise_level: float = 0.18,
    seed: int = 42,
) -> RawSensorDataset:
    """Generate realistic multi-day passive phone activity (m/s^2 ENMO-like) and ambient light (lux) data.

    Includes fundamental circadian rhythm, 12h & 8h harmonics (post-lunch dip & morning/evening peaks),
    optional phase shift (e.g., jet lag or delayed sleep phase from `shift_day`), sleep rest bouts, and noise.
    """
    rng = np.random.default_rng(seed)
    start = start_date or datetime(2026, 11, 10, 0, 0, 0)
    n_samples = int((days * 24 * 60) / epoch_minutes)
    timestamps = pd.date_range(start=start, periods=n_samples, freq=f"{max(1, int(round(epoch_minutes * 60)))}s")
    t_hours = np.arange(n_samples) * (epoch_minutes / 60.0)
    day_idx = (t_hours // 24.0).astype(int) + 1

    # Smooth or step phase shift starting on shift_day
    phase_offset_h = np.zeros_like(t_hours)
    if shift_day is not None and shift_hours != 0.0:
        # Smoothly transition over ~2 days or step on shift_day
        transition = np.clip((day_idx - shift_day + 1) / 2.0, 0.0, 1.0)
        phase_offset_h = shift_hours * transition

    effective_phase = t_hours - phase_offset_h
    omega = 2.0 * np.pi / tau_hours
    phi1 = -omega * acrophase_hour
    phi2 = -2.0 * omega * (acrophase_hour - 1.5)
    phi3 = -3.0 * omega * (acrophase_hour + 0.5)

    # Underlying circadian drive
    drive = (
        45.0
        + 36.0 * np.cos(omega * effective_phase + phi1)
        + 36.0 * harmonic_2_amp_ratio * np.cos(2.0 * omega * effective_phase + phi2)
        + 36.0 * harmonic_3_amp_ratio * np.cos(3.0 * omega * effective_phase + phi3)
    )

    # Sleep/rest gate: low activity around bathyphase (~acrophase + tau/2), free-running with tau_hours
    sleep_center = (acrophase_hour + 0.5 * tau_hours) % tau_hours
    phase_tod = effective_phase % tau_hours
    half_tau = 0.5 * tau_hours
    dist_from_sleep = np.abs(((phase_tod - sleep_center + half_tau) % tau_hours) - half_tau)
    awake_prob = 1.0 / (1.0 + np.exp(-(dist_from_sleep - 3.8) * 3.0))

    bursts = rng.gamma(shape=2.0, scale=12.0, size=n_samples) * (rng.random(n_samples) < 0.25)
    activity = np.clip(drive * awake_prob + bursts * awake_prob + rng.normal(0, 36.0 * noise_level, n_samples), 0.5, 250.0)
    # Minimal movement during deep rest
    activity = np.where(awake_prob < 0.25, rng.uniform(0.2, 4.0, n_samples), activity)

    # Ambient light (lux): tracks daytime + slight lead relative to activity
    light_acrophase = (acrophase_hour - 1.0) % tau_hours
    light_dist = np.abs(((phase_tod - light_acrophase + half_tau) % tau_hours) - half_tau)
    daylight = np.exp(-0.5 * (light_dist / 3.8) ** 2)
    outdoor_peaks = np.where((daylight > 0.5) & (rng.random(n_samples) < 0.12), rng.uniform(800, 4500, n_samples), 0.0)
    lux = np.clip(
        2.0 + 380.0 * daylight * awake_prob + outdoor_peaks * awake_prob + rng.normal(0, 15.0, n_samples),
        0.1,
        15000.0,
    )
    lux = np.where(awake_prob < 0.2, rng.uniform(0.0, 2.5, n_samples), lux)

    df = pd.DataFrame(
        {
            "timestamp": timestamps,
            "activity_raw": np.round(activity, 3),
            "lux": np.round(lux, 2),
        }
    )
    return RawSensorDataset(
        df=df,
        source_name=f"Synthetic_{days}d_tau{tau_hours:.1f}_shift{shift_hours:+.1f}h",
        source_type="synthetic",
        has_activity=True,
        has_light=True,
        metadata={
            "days": days,
            "tau_hours": tau_hours,
            "acrophase_hour": acrophase_hour,
            "shift_day": shift_day,
            "shift_hours": shift_hours,
        },
    )


class PhyphoxLiveRecorder:
    """Passive background recorder polling Phyphox Remote Access HTTP API (or simulated stream).

    Phyphox exposes:
      - `GET <base_url>/config` -> JSON experiment config and buffer names
      - `GET <base_url>/get?<buf1>&<buf2>` -> JSON buffer samples
    Recorded samples are continuously appended to a CSV file for durable multi-day passive logging.
    """

    def __init__(
        self,
        base_url: str = "http://192.168.1.50:8080",
        output_csv: Union[str, Path] = "recordings/phyphox_live.csv",
        poll_interval_sec: float = 5.0,
        simulate: bool = False,
    ) -> None:
        self.base_url = base_url.rstrip("/")
        self.output_csv = Path(output_csv)
        self.output_csv.parent.mkdir(parents=True, exist_ok=True)
        self.poll_interval_sec = max(0.5, float(poll_interval_sec))
        self.simulate = simulate

        self._stop_event = threading.Event()
        self._thread: Optional[threading.Thread] = None
        self._lock = threading.Lock()
        self.samples_recorded: int = 0
        self.last_error: Optional[str] = None
        self.last_sample: Optional[Dict[str, Any]] = None
        self._discovered_buffers: Optional[Dict[str, str]] = None

    @staticmethod
    def probe_phyphox(base_url: str, timeout: float = 3.0) -> Dict[str, Any]:
        """Inspect Phyphox `/config` endpoint to list available buffers."""
        url = f"{base_url.rstrip('/')}/config"
        with urlopen(url, timeout=timeout) as resp:
            data = json.loads(resp.read().decode("utf-8"))
        buffers = [b.get("name") for b in data.get("buffers", []) if b.get("name")]
        return {
            "title": data.get("title", "Phyphox Experiment"),
            "buffers": buffers,
            "raw": data,
        }

    def _discover_buffers(self) -> Dict[str, str]:
        """Map canonical fields (lux, ax, ay, az) to Phyphox buffer names."""
        if self._discovered_buffers is not None:
            return self._discovered_buffers
        info = self.probe_phyphox(self.base_url)
        buffers = info["buffers"]
        mapping: Dict[str, str] = {}
        for b in buffers:
            low = b.lower()
            if any(k in low for k in ("illum", "lux", "light")) and "lux" not in mapping:
                mapping["lux"] = b
            elif low in ("accx", "acc_x", "ax") or ("acc" in low and "x" in low and "time" not in low):
                mapping.setdefault("ax", b)
            elif low in ("accy", "acc_y", "ay") or ("acc" in low and "y" in low and "time" not in low):
                mapping.setdefault("ay", b)
            elif low in ("accz", "acc_z", "az") or ("acc" in low and "z" in low and "time" not in low):
                mapping.setdefault("az", b)
        self._discovered_buffers = mapping
        return mapping

    def poll_once(self) -> Optional[Dict[str, Any]]:
        """Fetch one passive snapshot from Phyphox (or generate one simulated tick) and log to CSV."""
        now = datetime.now()
        row: Dict[str, Any] = {"timestamp": now.isoformat(timespec="seconds")}

        if self.simulate:
            tod = now.hour + now.minute / 60.0 + now.second / 3600.0
            circ = 0.5 + 0.5 * np.cos(2.0 * np.pi * (tod - 14.5) / 24.0)
            row["ax"] = round(float(np.random.normal(0.15 * circ, 0.25)), 4)
            row["ay"] = round(float(np.random.normal(0.10 * circ, 0.25)), 4)
            row["az"] = round(float(9.81 + np.random.normal(0.15 * circ, 0.25)), 4)
            row["lux"] = round(float(max(0.5, 350.0 * circ + np.random.normal(0, 12.0))), 2)
        else:
            mapping = self._discover_buffers()
            if not mapping:
                raise RuntimeError("No light or accelerometer buffers discovered on Phyphox /config.")
            query = urlencode({buf: "" for buf in mapping.values()})
            url = f"{self.base_url}/get?{query}"
            with urlopen(url, timeout=4.0) as resp:
                payload = json.loads(resp.read().decode("utf-8"))
            buf_dict = payload.get("buffer", {})
            for canon, buf_name in mapping.items():
                arr = buf_dict.get(buf_name, {}).get("buffer", [])
                if arr:
                    # Use tail mean over recent samples in buffer for smooth passive epoch
                    tail = [float(x) for x in arr[-50:] if x is not None]
                    row[canon] = float(np.mean(tail)) if tail else np.nan
                else:
                    row[canon] = np.nan

        self._append_csv_row(row)
        with self._lock:
            self.samples_recorded += 1
            self.last_sample = row
            self.last_error = None
        return row

    def _append_csv_row(self, row: Dict[str, Any]) -> None:
        fieldnames = ["timestamp", "ax", "ay", "az", "lux"]
        write_header = not self.output_csv.exists() or self.output_csv.stat().st_size == 0
        with open(self.output_csv, "a", newline="", encoding="utf-8") as f:
            writer = csv.DictWriter(f, fieldnames=fieldnames)
            if write_header:
                writer.writeheader()
            writer.writerow({k: row.get(k, "") for k in fieldnames})

    def _loop(self) -> None:
        while not self._stop_event.is_set():
            try:
                self.poll_once()
            except Exception as exc:
                with self._lock:
                    self.last_error = str(exc)
            self._stop_event.wait(self.poll_interval_sec)

    def start(self) -> None:
        if self._thread and self._thread.is_alive():
            return
        self._stop_event.clear()
        self._thread = threading.Thread(target=self._loop, daemon=True)
        self._thread.start()

    def stop(self) -> None:
        self._stop_event.set()
        if self._thread:
            self._thread.join(timeout=2.0)

    def is_running(self) -> bool:
        return bool(self._thread and self._thread.is_alive() and not self._stop_event.is_set())

    def load_recorded_dataset(self) -> RawSensorDataset:
        if not self.output_csv.exists():
            raise FileNotFoundError(f"No live recording file exists yet at {self.output_csv}")
        return load_tabular_sensor_file(self.output_csv)
